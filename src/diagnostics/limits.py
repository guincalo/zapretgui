# Обрыв «на 16 КБ». ТСПУ режет соединения с зарубежными серверами после ~16 КБ
# данных. Считает он пакеты (около 25 в обе стороны), поэтому в байтах граница
# плавает: по замерам разных проверок — от 12 до 36 КБ. Одно окно на все проверки
# и на подбор стратегий: обрыв внутри него — блокировка по объёму.
FREEZE_MIN_BYTES = 12_000
FREEZE_MAX_BYTES = 36_000

DNS_TIMEOUT = 4.0
# Провайдер подменяет DNS не каждый раз: один запрос давал то «подмена», то
# «всё честно». Три запроса подряд ловят и такую подмену.
DNS_ATTEMPTS = 3
DOH_TIMEOUT = 5.0
# Сколько ждать остальные эталонные серверы после первого ответа. Обычно они отвечают за
# десятые доли секунды; закрытый провайдером сервер молчит весь срок.
REFERENCE_GRACE_S = 1.0
HTTPS_TIMEOUT = 5.0
READ_TIMEOUT = 3.0
# Сколько разных адресов сайта пробовать, прежде чем сказать «не открывается».
# Браузер перебирает все адреса из ответа DNS; у крупных сайтов их несколько,
# и закрытым бывает только один.
REACH_ADDRESSES = 4
# Сколько ждать первый адрес, прежде чем пробовать остальные одновременно с ним. Живой сайт
# отвечает за доли секунды; ждать молчащий адрес весь срок — по пять лишних секунд на каждый
# закрытый сайт.
HEAD_START_S = 1.5
# Пауза перед повтором на единственном адресе: потерянный пакет не должен
# выглядеть блокировкой.
RETRY_PAUSE_S = 1.0
# Сколько видеосерверов YouTube пробовать: плеер тоже переключается на запасные.
VIDEO_SERVERS = 3
DISCOVERY_TIMEOUT = 6.0
# Сколько читать страницу YouTube в поисках видеосервера, считая с первого куска:
# срок на каждый кусок есть и так, но медленная линия тянула двухмегабайтную
# страницу по куску без конца.
DISCOVERY_READ_BUDGET_S = 8.0
# Верхняя граница на всю проверку: дальше недопроверенное помечается как
# «нет ответа», а не подвешивает окно. Обычная проверка укладывается в треть
# срока; запас нужен, чтобы упавшие сайты успели перепровериться поодиночке —
# без этого сбой от нагрузки самой проверки сошёл бы за блокировку.
# Шаги идут по очереди, поэтому сроки с запасом: на линии, где закрыта половина сайтов,
# полная проверка занимала больше трёх минут и до места фильтра не доходила.
RUN_DEADLINE = 90.0
# Сколько сайтов проверять одновременно. Человек открывает сайты по одному-два;
# десять рукопожатий к разным адресам в одну секунду — узор проверяльщика,
# по которому программу узнаёт фильтр (``utils.probe_gate``).
SITES_AT_ONCE = 4
# Пауза между стартами сайтов: случайная, в этих пределах, в секундах.
SITE_START_GAP_S = (0.2, 0.9)
RUN_DEADLINE_ALL = 150.0
# Полная проверка ждёт ещё DNS-серверы и поиск места фильтра.
RUN_DEADLINE_FULL = 300.0
FILTER_MAX_TTL = 20
# Повторная проверка сайтов, которые не открылись: сколько сайтов перепроверять,
# сколько одновременно и сколько секунд должно оставаться до общего срока.
# Сколько в конце проверки ждать скачивания списка реестра РКН; не успел — берём прежний.
REGISTRY_WAIT_S = 8.0
RECHECK_SITES = 24
# Полная перепроверка сайта — десяток запросов, их немного разом.
RECHECK_AT_ONCE = 3
# Первый шаг перепроверки — один лёгкий запрос; на мёртвом сайте он ждёт весь срок,
# поэтому таких идёт больше разом.
RECHECK_LIGHT_AT_ONCE = 6
# Сколько вопросов к эталонным DNS-серверам идёт одновременно. Без предела
# четырнадцать сайтов разом открывали полторы сотни шифрованных соединений за
# треть секунды — на этом и тормозил компьютер в начале проверки.
REFERENCE_AT_ONCE = 32
# Сколько мелких проб сайтов (приветствия TLS, пакеты QUIC, запросы HTTP) идёт
# одновременно на весь прогон. Местных очередей много, а общего предела не было:
# на 10 сайтах разом набиралось до 150 сокетов, и слабый ПК, антивирус с проверкой
# HTTPS и домашний роутер не успевали.
NET_AT_ONCE_WEAK = 24
NET_AT_ONCE = 40
# Запас небольшой: повтор, который не успел, просто оставляет первый результат.
RECHECK_NEEDS_S = 12.0
# Сколько должно оставаться до общего срока, чтобы спросить сервер за рубежом («жив ли сайт снаружи»).
OUTSIDE_NEEDS_S = 20.0
FREEZE_READ_TIMEOUT = 4.0

# Откуда взят адрес, по которому проверяли сайт.
SOURCE_HOSTS = "hosts"
SOURCE_SYSTEM = "system"
SOURCE_REFERENCE = "reference"

# Качество передачи (``diagnostics.transfer_probe``): сайт может открыться и пройти окно обрыва,
# но отвечать с паузами или медленно — так выглядит кэш или канал, которые «спотыкаются».
# Один ответ ждали дольше этого срока, пока остальные приходили быстро: пауза.
TRANSFER_PAUSE_MS = 2_500
# Во сколько раз пауза должна превосходить обычный ответ. Иначе это просто далёкий сервер.
TRANSFER_PAUSE_RATIO = 20
# Обычный (медианный) ответ дольше этого: медленно в целом, а не отдельными запросами.
TRANSFER_SLOW_MEDIAN_MS = 1_200
# Скорость считается только по ответам с телом не меньше этого и дольше этого срока:
# у короткого ответа «скорость» — это задержка линии.
TRANSFER_SPEED_MIN_BODY = 16 * 1024
TRANSFER_SPEED_MIN_MS = 100
# Ниже этой скорости (КБ/с, около 1,2 Мбит/с) тело идёт медленно.
TRANSFER_SLOW_KBPS = 150
# Меньше стольких ответов по готовому соединению вывод о качестве не делается.
TRANSFER_MIN_SAMPLES = 3
