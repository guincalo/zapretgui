"""Build the guincalo/zapretgui fork on Windows.

1. write src/config/build_info.py and src/config/_build_secrets.py
   (no upstream secrets: no premium API URL, no update mirrors, no proxy presets);
2. fetch + verify the upstream runtime payload (fetch_payload.py);
3. PyInstaller -> dist/Zapret, moved to out/Zapret2/_internal;
4. zip out/Zapret2 -> out/Zapret2-<version>-clean-portable.zip.

Usage: python tools/fork_build/build.py <upstream-version>
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SRC = ROOT / "src"
OUT = ROOT / "out"


def run(*cmd: str, env: dict | None = None) -> None:
    print("+", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, cwd=ROOT, env=env)


def main() -> None:
    version = sys.argv[1]
    channel = "stable"
    (SRC / "config" / "build_info.py").write_text(
        f'"""Generated by tools/fork_build/build.py (guincalo/zapretgui fork)."""\n'
        f'APP_VERSION = "{version}"\nCHANNEL = "{channel}"\n',
        encoding="utf-8",
    )
    (SRC / "config" / "_build_secrets.py").write_text(
        '"""Generated by tools/fork_build/build.py. The fork ships no upstream build secrets."""\n'
        'PREMIUM_API_BASE_URL = ""\nUPDATE_SERVERS = []\nPROXY_PRESETS = []\nMTPROXY_LINK = ""\n',
        encoding="utf-8",
    )
    if OUT.exists():
        shutil.rmtree(OUT)
    app = OUT / "Zapret2"
    run(sys.executable, str(HERE / "fetch_payload.py"), version, str(app))

    import os

    env = dict(os.environ)
    icon = app / "system" / "ico" / "Zapret2.ico"
    if icon.exists():
        env["ZAPRET_ICON"] = str(icon)
    run(sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
        "--distpath", str(ROOT / "dist"), "--workpath", str(ROOT / "build"),
        str(HERE / "zapret.spec"), env=env)

    internal = app / "_internal"
    keep = internal / "install_manifest.json"
    saved = keep.read_bytes() if keep.exists() else None
    shutil.rmtree(internal, ignore_errors=True)
    shutil.copytree(ROOT / "dist" / "Zapret", internal)
    if saved is not None:
        keep.write_bytes(saved)
    (app / "user").mkdir(exist_ok=True)
    (app / "FORK-NOTICE.txt").write_text(
        "guincalo/zapretgui: Zapret 2 GUI rebuilt from source without update telemetry\n"
        "and without the upstream auto-updater. Engine/lists/lua/presets are the upstream\n"
        f"payload of release {version}, verified against its Ed25519-signed manifest.\n"
        "https://github.com/guincalo/zapretgui\n",
        encoding="utf-8",
    )
    archive = shutil.make_archive(str(OUT / f"Zapret2-{version}-clean-portable"), "zip", OUT, "Zapret2")
    print("built", archive, flush=True)


if __name__ == "__main__":
    main()
